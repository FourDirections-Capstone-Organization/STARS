using System.Text.Json;
using System.Text.Json.Serialization;
using Backend.Models;
using Backend.Models.Enums;

namespace Backend.Modules.PerformanceEvaluation;

/// <summary>
/// Strictly de-identified payload sent to the LLM for performance recommendation generation.
/// Strictly excludes any personal identifiable information (PII) such as employee names,
/// employee numbers, or database IDs.
/// </summary>
public class PerformanceAiPayload
{
    [JsonPropertyName("roleTitle")]
    public string? RoleTitle { get; set; }

    [JsonPropertyName("criterionScores")]
    public List<PerformanceAiCriterionScore> CriterionScores { get; set; } = new();

    [JsonPropertyName("kpiSnapshot")]
    public PerformanceAiKpiSnapshot? KpiSnapshot { get; set; }

    [JsonPropertyName("trimmedComments")]
    public List<string> TrimmedComments { get; set; } = new();
}

public class PerformanceAiCriterionScore
{
    [JsonPropertyName("sectionTitle")]
    public string SectionTitle { get; set; } = string.Empty;

    [JsonPropertyName("criterionTitle")]
    public string CriterionTitle { get; set; } = string.Empty;

    [JsonPropertyName("weight")]
    public double Weight { get; set; }

    [JsonPropertyName("selfScore")]
    public double? SelfScore { get; set; }

    [JsonPropertyName("managerScore")]
    public double? ManagerScore { get; set; }

    [JsonPropertyName("gap")]
    public double? Gap { get; set; }

    [JsonPropertyName("isOutlier")]
    public bool IsOutlier { get; set; }
}

public class PerformanceAiKpiSnapshot
{
    [JsonPropertyName("overallScore")]
    public double OverallScore { get; set; }

    [JsonPropertyName("metrics")]
    public List<PerformanceAiKpiMetric> Metrics { get; set; } = new();
}

public class PerformanceAiKpiMetric
{
    [JsonPropertyName("metricCode")]
    public string MetricCode { get; set; } = string.Empty;

    [JsonPropertyName("name")]
    public string Name { get; set; } = string.Empty;

    [JsonPropertyName("actualValue")]
    public double ActualValue { get; set; }

    [JsonPropertyName("targetValue")]
    public double TargetValue { get; set; }

    [JsonPropertyName("score")]
    public double Score { get; set; }
}

/// <summary>
/// Actionable goal / recommendation item generated by the AI.
/// Extensible: new fields can be added without breaking contract.
/// </summary>
public class PerformanceAiActionItem
{
    [JsonPropertyName("description")]
    public string Description { get; set; } = string.Empty;

    [JsonPropertyName("successMeasure")]
    public string SuccessMeasure { get; set; } = string.Empty;

    [JsonPropertyName("timeframe")]
    public string Timeframe { get; set; } = string.Empty;
}

/// <summary>
/// Structured, validated JSON response expected from the Groq LLM.
/// Extensibility: adding a new AI section requires only 1 new field here and 1 corresponding line in the system prompt.
/// </summary>
public class PerformanceAiResponse
{
    [JsonPropertyName("summary")]
    public string Summary { get; set; } = string.Empty;

    [JsonPropertyName("strengths")]
    public List<string> Strengths { get; set; } = new();

    [JsonPropertyName("improvementAreas")]
    public List<string> ImprovementAreas { get; set; } = new();

    [JsonPropertyName("actionItems")]
    public List<PerformanceAiActionItem> ActionItems { get; set; } = new();

    [JsonPropertyName("trainingTopics")]
    public List<string> TrainingTopics { get; set; } = new();
}

/// <summary>
/// Request DTO for updating an AI recommendation (approval, rejection, manual override, editing).
/// </summary>
public class UpdateAiRecommendationDTO
{
    public AiRecommendationStatus Status { get; set; }
    public string? Summary { get; set; }
    public List<string>? Strengths { get; set; }
    public List<string>? ImprovementAreas { get; set; }
    public List<PerformanceAiActionItem>? ActionItems { get; set; }
    public List<string>? TrainingTopics { get; set; }
    public string? ManualNotes { get; set; }
}

/// <summary>
/// DTO representation of an AI recommendation for API responses.
/// </summary>
public class AiRecommendationDTO
{
    public Guid Id { get; set; }
    public Guid ReviewId { get; set; }
    public Guid EmployeeId { get; set; }
    public AiRecommendationStatus Status { get; set; }
    public string? Summary { get; set; }
    public List<string> Strengths { get; set; } = new();
    public List<string> ImprovementAreas { get; set; } = new();
    public List<PerformanceAiActionItem> ActionItems { get; set; } = new();
    public List<string> TrainingTopics { get; set; } = new();
    public string? RawResponseJson { get; set; }
    public string? ManualNotes { get; set; }
    public Guid? ReviewedById { get; set; }
    public DateTime? ReviewedAt { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
}

/// <summary>
/// Result envelope for AI recommendation service operations.
/// </summary>
public class AiRecommendationServiceResult
{
    public bool IsSuccess { get; set; }
    public int StatusCode { get; set; } = 200;
    public string? ErrorMessage { get; set; }
    public AiRecommendation? Recommendation { get; set; }

    public static AiRecommendationServiceResult Success(AiRecommendation rec) =>
        new() { IsSuccess = true, StatusCode = 200, Recommendation = rec };

    public static AiRecommendationServiceResult Failure(int statusCode, string errorMessage, AiRecommendation? rec = null) =>
        new() { IsSuccess = false, StatusCode = statusCode, ErrorMessage = errorMessage, Recommendation = rec };
}

/// <summary>
/// Extension methods for converting domain AiRecommendation to DTO.
/// </summary>
public static class AiRecommendationExtensions
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase
    };

    public static AiRecommendationDTO ToDTO(this AiRecommendation rec)
    {
        return new AiRecommendationDTO
        {
            Id = rec.Id,
            ReviewId = rec.ReviewId,
            EmployeeId = rec.EmployeeId,
            Status = rec.Status,
            Summary = rec.Summary,
            Strengths = SafeDeserialize<List<string>>(rec.StrengthsJson) ?? new(),
            ImprovementAreas = SafeDeserialize<List<string>>(rec.ImprovementAreasJson) ?? new(),
            ActionItems = SafeDeserialize<List<PerformanceAiActionItem>>(rec.ActionItemsJson) ?? new(),
            TrainingTopics = SafeDeserialize<List<string>>(rec.TrainingTopicsJson) ?? new(),
            RawResponseJson = rec.RawResponseJson,
            ManualNotes = rec.ManualNotes,
            ReviewedById = rec.ReviewedById,
            ReviewedAt = rec.ReviewedAt,
            CreatedAt = rec.CreatedAt,
            UpdatedAt = rec.UpdatedAt
        };
    }

    private static T? SafeDeserialize<T>(string? json)
    {
        if (string.IsNullOrWhiteSpace(json)) return default;
        try
        {
            return JsonSerializer.Deserialize<T>(json, JsonOptions);
        }
        catch
        {
            return default;
        }
    }
}

